echo	Mostrar información.

$_GET	Recibir parámetros de la URL.

if / else / elseif	Tomar decisiones.

switch / case	Elegir entre varias opciones.

isset()	Comprobar si existe un valor y no es null.

empty()	Comprobar si un valor está vacío.

function	Crear una función.

return	Devolver un valor desde una función.

simplexml_load_file()	Leer un archivo XML.

foreach	Recorrer elementos de una colección.

addChild()	Añadir una etiqueta XML.

asXML()	Guardar un XML.

break	Salir de un bucle o de un switch.

in_array()	Buscar un valor en un array.

count()	Contar elementos.

array_push()	Añadir elementos al final de un array.

unset()	Eliminar una variable o un elemento.

array_values()	Reorganizar los índices numéricos de un array.

strtolower()	Convertir a minúsculas.

strtoupper()	Convertir a mayúsculas.

trim()	Eliminar espacios de los extremos.

strlen()	Contar bytes de un texto.

strpos()	Buscar la posición de un texto.

str_replace()	Sustituir un texto por otro.

substr()	Extraer una parte de un texto.